"""
Runs pytest and extracts detailed test results including:
- Repository name
- Branch
- Commit SHA
- Pipeline run identifier
- Execution timestamp
- Individual test names, results, execution times, failure details
- Total, passed, failed counts
- Overall test status

Sends this payload to the designated RECEIVER_URL.
"""

import json
import os
import subprocess
import sys
import urllib.error
import urllib.request
import xml.etree.ElementTree as ET
from datetime import datetime

BASE_DIR = os.path.abspath(os.path.dirname(__file__))
DEFAULT_RECEIVER_URL = os.environ.get("RECEIVER_URL", "http://127.0.0.1:5001/report")


def parse_junit_xml(xml_path):
    """Parses JUnit XML generated by pytest to get granular test details."""
    if not os.path.exists(xml_path):
        return {
            "total": 0, "passed": 0, "failed": 0, "errors": 0,
            "overall_status": "FAILED", "tests": []
        }

    tree = ET.parse(xml_path)
    root = tree.getroot()
    testsuite = root if root.tag == "testsuite" else root.find("testsuite")
    if testsuite is None:
        testsuite = root

    total = int(testsuite.get("tests", 0))
    failures = int(testsuite.get("failures", 0))
    errors = int(testsuite.get("errors", 0))
    skipped = int(testsuite.get("skipped", 0))
    passed = total - failures - errors - skipped
    overall_status = "PASS" if (failures + errors) == 0 and total > 0 else "FAIL"

    tests = []
    for tc in testsuite.iter("testcase"):
        name = tc.get("name", "")
        classname = tc.get("classname", "")
        tc_time = float(tc.get("time", 0))

        failure = tc.find("failure")
        error = tc.find("error")
        skip = tc.find("skipped")

        if failure is not None:
            res = "FAIL"
            msg = (failure.get("message") or failure.text or "").strip()
        elif error is not None:
            res = "ERROR"
            msg = (error.get("message") or error.text or "").strip()
        elif skip is not None:
            res = "SKIP"
            msg = skip.get("message", "").strip()
        else:
            res = "PASS"
            msg = None

        tests.append({
            "test_name": f"{classname}::{name}" if classname else name,
            "result": res,
            "duration": f"{tc_time:.3f}s",
            "failure_message": msg
        })

    return {
        "total": total,
        "passed": passed,
        "failed": failures + errors,
        "skipped": skipped,
        "overall_status": overall_status,
        "tests": tests
    }


def build_full_report(xml_file):
    test_data = parse_junit_xml(xml_file)

    report = {
        "repository_name": os.environ.get("GITHUB_REPOSITORY", "assignment-submission-portal"),
        "branch": os.environ.get("GITHUB_REF_NAME", "demo/phase5"),
        "commit_sha": os.environ.get("GITHUB_SHA", "local-test-run")[:10],
        "pipeline_run_id": os.environ.get("GITHUB_RUN_ID", "local-manual-run"),
        "pipeline_run_number": os.environ.get("GITHUB_RUN_NUMBER", "1"),
        "execution_timestamp": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "overall_status": test_data["overall_status"],
        "total": test_data["total"],
        "passed": test_data["passed"],
        "failed": test_data["failed"],
        "skipped": test_data["skipped"],
        "tests": test_data["tests"]
    }
    return report


def send_report(report, url=None):
    receiver_url = url or DEFAULT_RECEIVER_URL
    data = json.dumps(report, indent=4).encode("utf-8")
    req = urllib.request.Request(
        receiver_url,
        data=data,
        headers={"Content-Type": "application/json"},
        method="POST"
    )
    with urllib.request.urlopen(req, timeout=10) as response:
        return response.status


def main():
    xml_path = os.path.join(BASE_DIR, "test-results.xml")

    # Agar XML pehle se generated nahi hai, toh pytest chalayein
    if not os.path.exists(xml_path):
        print("Running pytest to generate test-results.xml...")
        subprocess.run([
            sys.executable, "-m", "pytest", "-v", f"--junitxml={xml_path}"
        ], cwd=BASE_DIR)

    report = build_full_report(xml_path)

    # Local preview ke liye bhi testreport.json file likh dein
    local_output = os.path.join(BASE_DIR, "testreport.json")
    with open(local_output, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=4)

    # Receiver URL decide karein (CLI argument ya env var)
    target_url = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_RECEIVER_URL
    print(f"Sending report to: {target_url}")
    print(f"Overall status: {report['overall_status']} ({report['passed']}/{report['total']} passed)")

    try:
        status = send_report(report, target_url)
        print(f"Report successfully delivered to receiver! (HTTP {status})")
    except Exception as error:
        print(f"WARNING: Could not connect to {target_url}: {error}")
        print("Agar local receiver chal raha hai toh ensure karein URL sahi hai.")

    return 0 if report["overall_status"] == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
